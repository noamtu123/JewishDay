package com.noamtu.jewishday.i18n

import android.annotation.SuppressLint
import android.app.LocaleManager
import android.content.Context
import android.content.res.Configuration
import android.content.res.Resources
import android.os.Build
import android.os.LocaleList
import androidx.annotation.RequiresApi
import androidx.core.content.edit
import com.noamtu.jewishday.BuildConfig
import java.util.Locale

/**
 * The app's language, as Android's per-app language setting.
 *
 * On Android 13 and later this *is* the system setting ([LocaleManager]): choosing a language in the
 * app or under Settings → Apps → JewishDay → Language is the same choice, the system keeps it and
 * backs it up, and every part of the app — activity, widgets, notification — gets resources in it.
 *
 * Android 12 and older have no such setting, so the choice is kept here and applied by hand: the
 * activity reads it as it is created ([wrap]), and code running on the application's context asks
 * [localizedContext] for a context in it.
 *
 * The languages offered are the app's translations ([supported]), generated by the build from the
 * `res/values-*` folders — so a new translation folder is all it takes for a language to appear in
 * the picker, and (through the generated locale config) in the system's settings.
 */
object AppLocales {
    /** BCP 47 tags of every translation, the default (`res/values`, English) first. */
    val supported: List<String> = BuildConfig.APP_LOCALES.toList()

    /** The language set for the app, or null when it follows the phone's. */
    fun applicationLocale(context: Context): String? =
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            localeManager(context).applicationLocales.takeUnless { it.isEmpty }?.get(0)?.toLanguageTag()?.let(::normalizeTag)
        } else {
            preferences(context).getString(LegacyLocaleKey, null)
        }

    /**
     * Sets the app's language — null to follow the phone. On Android 13+ the system then updates
     * every running part of the app; on older versions the caller recreates the activity.
     */
    fun setApplicationLocale(context: Context, tag: String?) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            localeManager(context).applicationLocales =
                if (tag == null) LocaleList.getEmptyLocaleList() else LocaleList.forLanguageTags(tag)
        } else {
            // commit, not apply: the activity is recreated straight after and must read the new value.
            preferences(context).edit(commit = true) {
                if (tag == null) remove(LegacyLocaleKey) else putString(LegacyLocaleKey, tag)
            }
        }
    }

    /** Whether the first launch of this install has settled the language; see `AppLanguageController`. */
    internal fun isInitialized(context: Context): Boolean = preferences(context).getBoolean(InitializedKey, false)

    internal fun markInitialized(context: Context) {
        preferences(context).edit { putBoolean(InitializedKey, true) }
    }

    /**
     * For an activity's `attachBaseContext`: the base context in the app's language. Android 13+ has
     * already given it one, so it is returned as it is.
     */
    fun wrap(base: Context): Context =
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) base else localizedContext(base)

    /**
     * [context] in the app's language. The application's own context follows the per-app language on
     * Android 13+, but only once the system has caught up with a change just made, and never on older
     * versions — so anything worded outside an activity goes through here.
     */
    // Lint warns that a Play app bundle split by language may not carry the language chosen; the app
    // ships as one APK holding every language, so there is nothing to download.
    @SuppressLint("AppBundleLocaleChanges")
    fun localizedContext(context: Context): Context {
        val tag = applicationLocale(context) ?: return context
        val current = context.resources.configuration.locales
        if (!current.isEmpty && normalizeTag(current[0].toLanguageTag()) == tag) return context
        val configuration = Configuration(context.resources.configuration).apply {
            setLocales(LocaleList.forLanguageTags(tag))
        }
        return context.createConfigurationContext(configuration)
    }

    /** The phone's own language, ignoring the app's: what a first launch starts in. */
    fun systemLanguage(): String =
        matchSupported(listOfNotNull(Resources.getSystem().configuration.locales.get(0)), supported)

    /** The locale of the translation [configuration] shows; see [matchSupported]. */
    fun displayLocale(configuration: Configuration): Locale =
        Locale.forLanguageTag(displayTag(configuration))

    fun displayTag(configuration: Configuration): String {
        val locales = configuration.locales
        return matchSupported((0 until locales.size()).map(locales::get), supported)
    }

    /** A language's own name for itself — "English", "עברית" — so the picker reads in every language. */
    fun displayName(tag: String): String {
        val locale = Locale.forLanguageTag(tag)
        return locale.getDisplayName(locale).replaceFirstChar { it.titlecase(locale) }
    }

    @RequiresApi(Build.VERSION_CODES.TIRAMISU)
    private fun localeManager(context: Context): LocaleManager = context.getSystemService(LocaleManager::class.java)

    private fun preferences(context: Context) =
        context.applicationContext.getSharedPreferences(PreferencesName, Context.MODE_PRIVATE)

    // Per install, and outside the backup like every SharedPreferences file here: the settings
    // DataStore carries the choice to a new phone, and the first launch there re-applies it.
    private const val PreferencesName = "app_locale"
    private const val LegacyLocaleKey = "language_tag"
    private const val InitializedKey = "initialized"
}

/**
 * Which of [supported] Android shows for [locales] — the user's languages in order of preference —
 * matched by language the way resources are: the first preferred language with a translation, and
 * the default (the first supported) when none has one.
 */
internal fun matchSupported(locales: List<Locale>, supported: List<String>): String {
    for (locale in locales) {
        val language = normalizeTag(locale.language)
        supported.firstOrNull { Locale.forLanguageTag(it).language.let(::normalizeTag) == language }?.let { return it }
    }
    return supported.first()
}

/** Hebrew, Indonesian and Yiddish still go by their old codes on some Android and Java versions. */
internal fun normalizeTag(tag: String): String {
    val parts = tag.split('-', '_')
    val language = when (parts.first()) {
        "iw" -> "he"
        "in" -> "id"
        "ji" -> "yi"
        else -> parts.first()
    }
    return (listOf(language) + parts.drop(1)).joinToString("-")
}
